package org.example;

public class Socio {
    String nombre;
    String apellidos;
    int edad;
    String direccion;
    int telefono;

    Socio(String nombre, String apellidos, int edad, String direccion, int telefono) {
        this.nombre = nombre;
        this.apellidos = apellidos;
        this.edad = edad;
        this.direccion = direccion;
        this.telefono = telefono;
    }
}
